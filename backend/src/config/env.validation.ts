import * as Joi from 'joi';

export const envValidationSchema = Joi.object({
  NODE_ENV: Joi.string().valid('development', 'test', 'production').default('development'),
  PORT: Joi.number().port().default(3000),
  DB_HOST: Joi.string().required(),
  DB_PORT: Joi.number().port().default(3306),
  DB_USER: Joi.string().required(),
  // Empty password is allowed in development (local Docker), but blocked in production.
  DB_PASSWORD: Joi.when('NODE_ENV', {
    is: 'production',
    then: Joi.string().min(1).required(),
    otherwise: Joi.string().allow('').required(),
  }),
  DB_NAME: Joi.string().required(),
  ALLOWED_ORIGINS: Joi.string().optional(),
  FRONTEND_URL: Joi.string().uri().optional(),
  BACKEND_PUBLIC_URL: Joi.string().uri().optional(),
  BACKEND_INTERNAL_URL: Joi.string().uri().optional(),
  MOODLE_BASE_URL: Joi.string().uri().optional(),
  MOODLE_PUBLIC_URL: Joi.string().uri().optional(),
  // In production the Moodle (service-account) token must be present and meet a minimum length.
  MOODLE_TOKEN: Joi.when('NODE_ENV', {
    is: 'production',
    then: Joi.string().min(32).required(),
    otherwise: Joi.string().optional(),
  }),
  // Per-user Moodle WS token infra (native quiz/assign). Optional — feature disabled if unset.
  MOODLE_DB_HOST: Joi.string().optional(),
  MOODLE_DB_PORT: Joi.number().port().default(3306),
  MOODLE_DB_USER: Joi.string().optional(),
  MOODLE_DB_PASSWORD: Joi.string().allow('').optional(),
  MOODLE_DB_NAME: Joi.string().optional(),
  MOODLE_WS_SERVICE_ID: Joi.number().default(4),
  MOODLE_WS_CREATOR_ID: Joi.number().default(2),
  JWT_SECRET: Joi.string().min(32).required(),
  // Set to 'true' only when Moodle direct-login is required; SSO via getMoodleSsoUrl is the default.
  ENABLE_MOODLE_PASSWORD_SYNC: Joi.string().valid('true', 'false').default('false'),
  RATE_LIMIT_LOGIN_TTL: Joi.number().default(60000),
  RATE_LIMIT_LOGIN_LIMIT: Joi.number().default(5),
  UNIVERSITY_DIRECTORY_MODE: Joi.string().valid('manual', 'msg').default('manual'),
  // BUU fields are required whenever MSG mode is active (any environment).
  BUU_DOMAIN: Joi.when('UNIVERSITY_DIRECTORY_MODE', {
    is: 'msg',
    then: Joi.string().uri().required(),
    otherwise: Joi.string().uri().optional(),
  }),
  BUU_REQUEST_CLIENT_ID: Joi.when('UNIVERSITY_DIRECTORY_MODE', {
    is: 'msg',
    then: Joi.string().required(),
    otherwise: Joi.string().optional(),
  }),
  BUU_REQUEST_CLIENT_SECRET: Joi.when('UNIVERSITY_DIRECTORY_MODE', {
    is: 'msg',
    then: Joi.string().required(),
    otherwise: Joi.string().optional(),
  }),
  BUU_REQUEST_TOKEN_PATH: Joi.string().optional(),
  BUU_REQUEST_GRANT_TYPE: Joi.string().optional(),
  BUU_REQUEST_AUTH_USERID: Joi.string().optional(),
  BUU_UPLOAD_FILE_PROVISION_KEY: Joi.string().optional(),
  BUU_GET_FILE_LIST_PROVISION_KEY: Joi.string().optional(),
  BUU_GET_PUBLIC_FILE_PROVISION_KEY: Joi.string().optional(),
  BUU_DELETE_FILE_PROVISION_KEY: Joi.string().optional(),
  BUU_TIME_STAMP_PROVISION_KEY: Joi.string().optional(),
  BUU_DS_PREFIX_PROVISION_KEY: Joi.string().optional(),
  BUU_CREATE_SHORT_URL_PROVISION_KEY: Joi.string().optional(),
  BUU_GET_ORIGINAL_URL_PROVISION_KEY: Joi.string().optional(),
  BUU_SEND_EMAIL_PROVISION_KEY: Joi.when('UNIVERSITY_DIRECTORY_MODE', {
    is: 'msg',
    then: Joi.string().required(),
    otherwise: Joi.string().optional(),
  }),
  PLATFORM_GATEWAY_DOMAIN: Joi.string().uri().optional(),
  PLATFORM_GATEWAY_BUCKET: Joi.string().optional(),
  PLATFORM_GATEWAY_CLIENT_ID: Joi.string().optional(),
  PLATFORM_GATEWAY_CLIENT_SECRET: Joi.string().optional(),
  PLATFORM_GATEWAY_TOKEN_PATH: Joi.string().optional(),
  PLATFORM_GATEWAY_GRANT_TYPE: Joi.string().optional(),
  PLATFORM_GATEWAY_AUTHENTICATED_USERID: Joi.string().optional(),
  PLATFORM_GATEWAY_UPLOAD_FILE_PATH: Joi.string().optional(),
  PLATFORM_GATEWAY_UPLOAD_FILE_SCOPE: Joi.string().optional(),
  PLATFORM_GATEWAY_UPLOAD_FILE_PROVISION_KEY: Joi.string().optional(),
  PLATFORM_GATEWAY_GET_FILE_LIST_PATH: Joi.string().optional(),
  PLATFORM_GATEWAY_GET_FILE_LIST_SCOPE: Joi.string().optional(),
  PLATFORM_GATEWAY_GET_FILE_LIST_PROVISION_KEY: Joi.string().optional(),
  PLATFORM_GATEWAY_GET_PUBLIC_FILE_PATH: Joi.string().optional(),
  PLATFORM_GATEWAY_GET_PUBLIC_FILE_SCOPE: Joi.string().optional(),
  PLATFORM_GATEWAY_GET_PUBLIC_FILE_PROVISION_KEY: Joi.string().optional(),
  PLATFORM_GATEWAY_DELETE_FILE_PATH: Joi.string().optional(),
  PLATFORM_GATEWAY_DELETE_FILE_SCOPE: Joi.string().optional(),
  PLATFORM_GATEWAY_DELETE_FILE_PROVISION_KEY: Joi.string().optional(),
  PLATFORM_GATEWAY_SEND_EMAIL_PATH: Joi.string().optional(),
  PLATFORM_GATEWAY_SEND_EMAIL_SCOPE: Joi.string().optional(),
  PLATFORM_GATEWAY_SEND_EMAIL_PROVISION_KEY: Joi.string().optional(),
  PLATFORM_GATEWAY_TIME_STAMP_PATH: Joi.string().optional(),
  PLATFORM_GATEWAY_TIME_STAMP_SCOPE: Joi.string().optional(),
  PLATFORM_GATEWAY_TIME_STAMP_PROVISION_KEY: Joi.string().optional(),
  PLATFORM_GATEWAY_DS_PREFIX_PATH: Joi.string().optional(),
  PLATFORM_GATEWAY_DS_PREFIX_SCOPE: Joi.string().optional(),
  PLATFORM_GATEWAY_DS_PREFIX_PROVISION_KEY: Joi.string().optional(),
  PLATFORM_GATEWAY_CREATE_SHORT_URL_PATH: Joi.string().optional(),
  PLATFORM_GATEWAY_CREATE_SHORT_URL_SCOPE: Joi.string().optional(),
  PLATFORM_GATEWAY_CREATE_SHORT_URL_PROVISION_KEY: Joi.string().optional(),
  PLATFORM_GATEWAY_GET_ORIGINAL_URL_PATH: Joi.string().optional(),
  PLATFORM_GATEWAY_GET_ORIGINAL_URL_SCOPE: Joi.string().optional(),
  PLATFORM_GATEWAY_GET_ORIGINAL_URL_PROVISION_KEY: Joi.string().optional(),
});

function loadDotEnv(path: string) {
  if (!existsSync(path)) {
    return;
  }

  for (const line of readFileSync(path, 'utf8').split(/\r?\n/)) {
    const match = line.match(/^\s*([\w.-]+)\s*=\s*(.*)?\s*$/);

    if (!match) {
      continue;
    }

    const key = match[1];
    const value = match[2] ?? '';

    if (!key || key.startsWith('#') || process.env[key] !== undefined) {
      continue;
    }

    process.env[key] = value.replace(/^(['"])(.*)\1$/, '$2');
  }
}

